import { z } from "zod";

const envSchema = z.object({
  SHOPIFY_STORE_DOMAIN: z.string().trim().min(1).optional(),
  SHOPIFY_STOREFRONT_ACCESS_TOKEN: z.string().trim().min(1).optional(),
  SHOPIFY_API_VERSION: z.string().regex(/^\d{4}-\d{2}$/).default("2026-10"),
  SHOPIFY_WEBHOOK_SECRET: z.string().min(1).optional(),
  SHOPIFY_CUSTOMER_ACCOUNT_CLIENT_ID: z.string().min(1).optional(),
  SHOPIFY_CUSTOMER_ACCOUNT_AUTH_URL: z.string().url().optional(),
  SHOPIFY_CUSTOMER_ACCOUNT_TOKEN_URL: z.string().url().optional(),
  SHOPIFY_CUSTOMER_ACCOUNT_GRAPHQL_URL: z.string().url().optional(),
  SHOPIFY_CUSTOMER_ACCOUNT_REDIRECT_URI: z.string().url().optional(),
  NEXT_PUBLIC_SITE_URL: z.string().url().default("http://localhost:3000"),
  NEXT_PUBLIC_GA_ID: z.string().optional(),
  NEXT_PUBLIC_META_PIXEL_ID: z.string().optional(),
  FREE_SHIPPING_THRESHOLD_USD: z.coerce.number().positive().default(299),
});

export const env = envSchema.parse({
  SHOPIFY_STORE_DOMAIN: process.env.SHOPIFY_STORE_DOMAIN,
  SHOPIFY_STOREFRONT_ACCESS_TOKEN: process.env.SHOPIFY_STOREFRONT_ACCESS_TOKEN,
  SHOPIFY_API_VERSION: process.env.SHOPIFY_API_VERSION,
  SHOPIFY_WEBHOOK_SECRET: process.env.SHOPIFY_WEBHOOK_SECRET,
  SHOPIFY_CUSTOMER_ACCOUNT_CLIENT_ID: process.env.SHOPIFY_CUSTOMER_ACCOUNT_CLIENT_ID,
  SHOPIFY_CUSTOMER_ACCOUNT_AUTH_URL: process.env.SHOPIFY_CUSTOMER_ACCOUNT_AUTH_URL,
  SHOPIFY_CUSTOMER_ACCOUNT_TOKEN_URL: process.env.SHOPIFY_CUSTOMER_ACCOUNT_TOKEN_URL,
  SHOPIFY_CUSTOMER_ACCOUNT_GRAPHQL_URL: process.env.SHOPIFY_CUSTOMER_ACCOUNT_GRAPHQL_URL,
  SHOPIFY_CUSTOMER_ACCOUNT_REDIRECT_URI: process.env.SHOPIFY_CUSTOMER_ACCOUNT_REDIRECT_URI,
  NEXT_PUBLIC_SITE_URL: process.env.NEXT_PUBLIC_SITE_URL,
  NEXT_PUBLIC_GA_ID: process.env.NEXT_PUBLIC_GA_ID,
  NEXT_PUBLIC_META_PIXEL_ID: process.env.NEXT_PUBLIC_META_PIXEL_ID,
  FREE_SHIPPING_THRESHOLD_USD: process.env.FREE_SHIPPING_THRESHOLD_USD,
});

export const shopifyConfigured = Boolean(
  env.SHOPIFY_STORE_DOMAIN && env.SHOPIFY_STOREFRONT_ACCESS_TOKEN,
);
